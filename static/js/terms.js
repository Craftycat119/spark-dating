const ORDER = ["terms", "rules", "privacy", "consent", "biometric", "sexuality", "parent"];
export const LEGAL_DOCS = ORDER.map((k) => ({ key: k, title: DOCS[k].title }));

const articleHtml = (key) => {
  const doc = DOCS[key] || DOCS.terms;
  const many = doc.sections.length > 1;
  return `
  <article class="terms" translate="no">
    <h1>${doc.title}</h1>
    <p class="muted">Сервис COFI · Редакция от ${UPDATED}</p>
    ${TEST_MODE}
    ${many ? `<nav class="terms-toc">${doc.sections.map(([title], i) => `<a href="#terms-${i + 1}" data-jump="${i + 1}">${i + 1}. ${title}</a>`).join("")}</nav>` : ""}
    ${doc.sections.map(([title, body], i) => `<section data-sec="${i + 1}"><h2>${many ? `${i + 1}. ` : ""}${title}</h2>${body}</section>`).join("")}
    <nav class="terms-docs"><h2>Все документы</h2>${ORDER.filter((k) => k !== key).map((k) => link(k, DOCS[k].title)).join("")}</nav>
  </article>`;
};

// ссылки оглавления прокручивают текст, а не меняют маршрут
function bindToc(root) {
  root.querySelectorAll("[data-jump]").forEach((a) => (a.onclick = (e) => {
    e.preventDefault();
    root.querySelector(`[data-sec="${a.dataset.jump}"]`).scrollIntoView({ behavior: "smooth", block: "start" });
  }));
}

/** Отдельная страница #/terms или #/legal/<документ>: на неё можно дать ссылку. */
export function renderTerms({ screen, go, doc = "terms" }) {
  const root = screen(`<button type="button" class="back-btn" data-step-back>${icons.back}<span>Назад</span></button>${articleHtml(doc)}`,
    { nav: false, cls: "terms-screen" });
  $("[data-step-back]", root).onclick = () => (history.length > 1 ? history.back() : go("#/"));
  bindToc(root);
  window.scrollTo(0, 0);
}

/** Документ поверх текущего экрана: при регистрации введённые данные не теряются. */
export function openTerms(doc = "terms") {
  document.querySelector(".terms-overlay")?.remove();
  const el = h(`<div class="overlay terms-overlay" role="dialog" aria-label="${DOCS[doc]?.title || "Документ"}">
    <div class="terms-sheet">
      <button type="button" class="icon-btn terms-close" aria-label="Закрыть">${icons.x}</button>
      ${articleHtml(doc)}
      <button type="button" class="btn block terms-ok">Понятно</button>
    </div></div>`);
  const close = () => el.remove();
  $(".terms-close", el).onclick = close;
  $(".terms-ok", el).onclick = close;
  bindToc(el);
  document.body.append(el);
}

/** Ссылка с data-terms или data-doc="<документ>" открывает документ поверх экрана. */
document.addEventListener("click", (e) => {
  const a = e.target.closest?.("[data-terms], [data-doc]");
  if (!a) return;
  e.preventDefault();
  openTerms(a.dataset.doc || "terms");
});
