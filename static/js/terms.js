const articleHtml = () => `
  <article class="terms" translate="no">
    <h1>Пользовательское соглашение COFI</h1>
    <p class="muted">Редакция от ${UPDATED}</p>
    <nav class="terms-toc">${SECTIONS.map(([title], i) => `<a href="#terms-${i + 1}" data-jump="${i + 1}">${i + 1}. ${title}</a>`).join("")}</nav>
    ${SECTIONS.map(([title, body], i) => `<section data-sec="${i + 1}"><h2>${i + 1}. ${title}</h2>${body}</section>`).join("")}
  </article>`;

// ссылки оглавления прокручивают текст, а не меняют маршрут
function bindToc(root) {
  root.querySelectorAll("[data-jump]").forEach((a) => (a.onclick = (e) => {
    e.preventDefault();
    root.querySelector(`[data-sec="${a.dataset.jump}"]`).scrollIntoView({ behavior: "smooth", block: "start" });
  }));
}

/** Отдельная страница #/terms: на неё можно дать ссылку. */
export function renderTerms({ screen, go }) {
  const root = screen(`<button type="button" class="back-btn" data-step-back>${icons.back}<span>Назад</span></button>${articleHtml()}`,
    { nav: false, cls: "terms-screen" });
  $("[data-step-back]", root).onclick = () => go("#/");
  bindToc(root);
  window.scrollTo(0, 0);
}

/** Соглашение поверх текущего экрана: при регистрации введённые данные не теряются. */
export function openTerms() {
  const el = h(`<div class="overlay terms-overlay" role="dialog" aria-label="Пользовательское соглашение">
    <div class="terms-sheet">
      <button type="button" class="icon-btn terms-close" aria-label="Закрыть">${icons.x}</button>
      ${articleHtml()}
      <button type="button" class="btn block terms-ok">Понятно</button>
    </div></div>`);
  const close = () => el.remove();
  $(".terms-close", el).onclick = close;
  $(".terms-ok", el).onclick = close;
  bindToc(el);
  document.body.append(el);
}

/** Любая ссылка с data-terms открывает соглашение поверх экрана. */
document.addEventListener("click", (e) => {
  const a = e.target.closest?.("[data-terms]");
  if (!a) return;
  e.preventDefault();
  openTerms();
});
